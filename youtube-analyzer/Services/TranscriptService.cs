using YoutubeAnalyzer.Models;
using YoutubeExplode;

namespace YoutubeAnalyzer.Services;

internal sealed class TranscriptService : IDisposable
{
    private readonly YoutubeClient _youtube = new();

    public async Task<VideoTranscript?> GetTranscriptAsync(
        string videoId,
        string preferredLanguage,
        CancellationToken cancellationToken = default)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(videoId);
        ArgumentException.ThrowIfNullOrWhiteSpace(preferredLanguage);

        var manifest = await NetworkRetry.ExecuteAsync(
            token => _youtube.Videos.ClosedCaptions
                .GetManifestAsync(videoId, token)
                .AsTask(),
            $"fetching transcript tracks for video {videoId}",
            cancellationToken);

        if (manifest.Tracks.Count == 0)
        {
            return null;
        }

        var languagePrefix = $"{preferredLanguage}-";
        var trackInfo = manifest.TryGetByLanguage(preferredLanguage)
            ?? manifest.Tracks.FirstOrDefault(track =>
                track.Language.Code.StartsWith(
                    languagePrefix,
                    StringComparison.OrdinalIgnoreCase))
            ?? manifest.Tracks[0];

        var track = await NetworkRetry.ExecuteAsync(
            token => _youtube.Videos.ClosedCaptions.GetAsync(trackInfo, token).AsTask(),
            $"downloading transcript for video {videoId}",
            cancellationToken);

        return new VideoTranscript
        {
            VideoId = videoId,
            LanguageCode = trackInfo.Language.Code,
            LanguageName = trackInfo.Language.Name,
            IsAutoGenerated = trackInfo.IsAutoGenerated,
            Segments = track.Captions
                .Select(caption => new TranscriptSegment
                {
                    StartSeconds = caption.Offset.TotalSeconds,
                    DurationSeconds = caption.Duration.TotalSeconds,
                    Text = caption.Text
                })
                .ToList()
        };
    }

    public void Dispose() => _youtube.Dispose();
}
